#include <stdio.h>//Biblioteca de entrada e saída de dados  

  

int main() {//inicio da função principal  

    int i;//Variável de controle da repetição. 

  

    for(i = 1; i <= 10; i++) {//O comando for possui três partes: 

  

//* i = 1 ? começa em 1. 

//* i <= 10 ? repete até 10. 

//* i++ ? aumenta 1 a cada volta. 

        printf("%d\n", i);//Mostra o valor atual de i. 

    } 

  

    return 0;//Finaliza o programa 

} 
